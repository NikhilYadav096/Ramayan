import { suggestedQuestions } from "../chatbot/knowledge";
import { hasRemote } from "../chatbot/engine";
import { gsap } from "../lib/scroll";
import { useGsap } from "../hooks/useGsap";

export const openChat = (question?: string) =>
  window.dispatchEvent(new CustomEvent("open-chat", { detail: { question } }));

export default function AskSection() {
  const ref = useGsap<HTMLElement>(() => {
    gsap.from(".ask__inner > *", {
      y: 30,
      opacity: 0,
      duration: 0.9,
      stagger: 0.1,
      ease: "power3.out",
      scrollTrigger: { trigger: ".ask__inner", start: "top 78%", once: true },
    });
  });

  return (
    <section id="ask" className="ask section" ref={ref} aria-labelledby="ask-title">
      <div className="wrap ask__inner">
        <p className="eyebrow">Ask Ramayana</p>
        <h2 id="ask-title" className="h2">Curious about <em>anything</em> in the epic?</h2>
        <p className="section-head__lede">
          Ask about characters, events, Sanskrit terms or teachings.{" "}
          {hasRemote
            ? "Answers are generated by a connected AI service grounded in a curated knowledge base."
            : "Answers come from a curated knowledge base, not a live AI model. If it doesn't know, it says so."}
        </p>
        <ul className="ask__chips">
          {suggestedQuestions.map((q) => (
            <li key={q}>
              <button className="chip" onClick={() => openChat(q)}>{q}</button>
            </li>
          ))}
        </ul>
        <button className="btn" onClick={() => openChat()}>Open the guide</button>
      </div>
    </section>
  );
}
